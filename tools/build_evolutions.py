"""Build vampire_survivors_env/features/evolutions.json from the wiki's Evolution page.

    python tools/build_evolutions.py [--wikitext saved_page.wiki]

Reads the page's wikitext (https://vampire.survivors.wiki/w/Evolution?action=raw),
takes every table row of the form "ingredients = result", and maps each
{{Sprite|Name}} onto a vocab.json key by display name.  Morphs (which need a
character and relics) and Penshin Fatcha's pick-one row are skipped, and the
Treasure Chest a gift row names is dropped: every evolution needs a chest.
Fails if any other name is missing from the vocabulary.
"""

import argparse
import json
import re
import urllib.request
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VOCAB = ROOT / "vampire_survivors_env" / "features" / "vocab.json"
OUT = ROOT / "vampire_survivors_env" / "features" / "evolutions.json"
URL = "https://vampire.survivors.wiki/w/Evolution?action=raw"

SPRITE = re.compile(r"\{\{Sprite\|([^|}]+)")
HEADING = re.compile(r"^(=+)\s*(.*?)\s*=+\s*$")
KINDS = {"Evolutions": "evolution", "Unions": "union", "Union": "union", "Gifts": "gift"}
NOT_INGREDIENTS = {"Treasure Chest 2"}
DLC_SECTIONS = {
    "Base game": None,
    "Legacy of the Moonspell": "lm",
    "Legacy of the Bloodmoon": "bm",
    "Tides of the Foscari": "tf",
    "Emergency Meeting": "em",
    "Operation Guns": "og",
    "Ode to Castlevania": "oc",
    "Emerald Diorama": "ed",
    "Ante Chamber": "ac",
}


def rows(wikitext: str):
    """(dlc section, table kind, row text) for every table row."""
    section = kind = None
    row = None
    for line in wikitext.splitlines():
        m = HEADING.match(line)
        if m:
            if row:
                yield row
            row = None
            level, title = len(m.group(1)), m.group(2)
            if level == 3:
                section = title
            elif level == 4:
                kind = title
            continue
        if line.startswith(("|-", "{|", "|}")):
            if row:
                yield row
            row = (section, kind, "") if line.startswith("|-") else None
        elif row:
            row = (row[0], row[1], row[2] + "\n" + line)
    if row:
        yield row


def build(wikitext: str, vocab: dict) -> list[dict]:
    by_name = {e["name"].lower(): e["key"] for e in vocab["entries"] if e["name"]}
    recipes, missing = [], set()
    for section, kind, text in rows(wikitext):
        if "'''='''" not in text or kind not in KINDS:
            continue
        left, right = text.split("'''='''", 1)
        names = [n.strip() for n in SPRITE.findall(left) if n.strip() not in NOT_INGREDIENTS]
        results = [n.strip() for n in SPRITE.findall(right)]
        if len(results) != 1:  # Penshin Fatcha: pick one of several
            continue
        for n in names + results:
            if n.lower() not in by_name:
                missing.add(n)
        if section not in DLC_SECTIONS:
            raise ValueError(f"unknown wiki section {section!r}; add it to DLC_SECTIONS")
        recipes.append({
            "result": by_name.get(results[0].lower(), results[0]),
            "kind": KINDS[kind],
            "ingredients": [by_name.get(n.lower(), n) for n in names],
            "max_level_passives": "max level" in left.lower(),
            "dlc": DLC_SECTIONS[section],
        })
    if missing:
        raise ValueError(f"names not in vocab.json: {sorted(missing)}")
    return recipes


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--wikitext", type=Path, help="a saved copy of the page's wikitext, instead of fetching it")
    args = ap.parse_args()
    if args.wikitext:
        wikitext = args.wikitext.read_text(encoding="utf-8")
    else:
        req = urllib.request.Request(URL, headers={"User-Agent": "vampire-survivors-rl-environment"})
        with urllib.request.urlopen(req, timeout=30) as resp:
            wikitext = resp.read().decode("utf-8")
    recipes = build(wikitext, json.loads(VOCAB.read_text(encoding="utf-8")))
    doc = {
        "comment": "Generated by tools/build_evolutions.py; do not edit by hand.  Keys are vocab.json keys. "
                   "Every ingredient must be owned (weapons at max level, and passives too when "
                   "max_level_passives) when a qualifying chest is opened.",
        "source": f"vampire.survivors.wiki 'Evolution' page (fetched {date.today().isoformat()}); morphs and Penshin Fatcha omitted",
        "recipes": recipes,
    }
    OUT.write_text(json.dumps(doc, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {len(recipes)} recipes to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
